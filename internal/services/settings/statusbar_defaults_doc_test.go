package settings

import (
	"os"
	"path/filepath"
	"strconv"
	"strings"
	"testing"

	"github.com/crevissepartners/projmux/internal/services/tmuxconfig"
)

// TestSDKDocHelperSentenceMatchesRecentWindowHook keeps the SetStatusbarResources
// helper sentence in docs/sdk.md true to the generated config: the expected
// command, run-shell form and hook events come from
// TmuxRecentWindowRecordHookLines, not from copies of its lines.
func TestSDKDocHelperSentenceMatchesRecentWindowHook(t *testing.T) {
	const helper = "<helper>"
	lines := tmuxconfig.TmuxRecentWindowRecordHookLines(helper)
	if len(lines) != 3 {
		t.Fatalf("recent window record lines = %q, want two hooks and one source-time run", lines)
	}
	runShell, quoted, ok := strings.Cut(lines[2], " \"")
	if !ok || !strings.HasPrefix(runShell, "run-shell") {
		t.Fatalf("source-time line = %q, want a run-shell command", lines[2])
	}
	command, err := strconv.Unquote("\"" + quoted)
	if err != nil {
		t.Fatalf("source-time command %q: %v", lines[2], err)
	}
	command, _, _ = strings.Cut(command, " >")
	if !strings.HasPrefix(command, helper+" ") {
		t.Fatalf("source-time command = %q, want the helper", command)
	}
	events := []string{}
	for _, line := range lines[:2] {
		fields := strings.Fields(line)
		if len(fields) < 4 || fields[0] != "set-hook" || fields[1] != "-g" {
			t.Fatalf("hook line = %q, want set-hook -g <event>", line)
		}
		if body := strings.Join(fields[3:], " "); !strings.Contains(body, runShell) || !strings.Contains(body, command) {
			t.Fatalf("hook %s body = %q, want %s %s", fields[2], body, runShell, command)
		}
		events = append(events, fields[2])
	}

	content, err := os.ReadFile(filepath.Join("..", "..", "..", "docs", "sdk.md"))
	if err != nil {
		t.Fatal(err)
	}
	doc := strings.Join(strings.Fields(string(content)), " ")
	start := strings.Index(doc, "Missing or invalid helper input fails preparation")
	end := strings.Index(doc, "Exact generated bytes skip a rewrite")
	if start < 0 || end < start {
		t.Fatal("docs/sdk.md lost the SetStatusbarResources helper paragraph")
	}
	paragraph := doc[start:end]
	want := []string{
		"never executes the helper itself",
		"When tmux sources that config, it starts `" + command + "` once in the background with `" + runShell + "`",
		"`" + events[0] + "` and `" + events[1] + "` hooks start it again later",
		"neither waits for that command nor reports its result",
	}
	for _, phrase := range want {
		if !strings.Contains(paragraph, phrase) {
			t.Fatalf("helper paragraph %q is missing %q", paragraph, phrase)
		}
	}
	if strings.Contains(paragraph, "does not execute it") {
		t.Fatalf("helper paragraph still says the helper is not executed: %q", paragraph)
	}
}
