type recordingShellRunner struct {
	env  []string
	name string
	args []string
}

func (r *recordingShellRunner) run(_ context.Context, env []string, name string, args ...string) error {
	r.env = append([]string(nil), env...)
	r.name = name
	r.args = append([]string(nil), args...)
	return nil
}

type shellUpdateRunnerFunc func(options intfzf.Options) (intfzf.Result, error)

func (f shellUpdateRunnerFunc) Run(options intfzf.Options) (intfzf.Result, error) {
	return f(options)
}
